//
//  MeetingTitleService.swift
//  WhisperShortcut
//
//  App-level meeting-title generation, independent of any chat window.
//
//  The title used to be generated only inside `ChatViewModel`, which needs an open chat window.
//  The chat window auto-closes on focus loss (`chatCloseOnFocusLoss`), so at summary-ready time
//  that sink was usually gone and the meeting stayed untitled until the user opened the tab.
//
//  `MenuBarController` is the only live observer of `.chatMeetingSummaryReady`. It calls this
//  service, which writes the title and posts `.chatSessionTitleChanged`. An open chat copies
//  that title into its in-memory session; otherwise the next `store.save(session)` would persist
//  the still-nil copy over the title just written. The chat backfill (opening a meeting tab
//  whose summary is already on disk) calls this same function. Both entry points early-return
//  once a real title exists, so at most one title call runs and a manual rename is never overwritten.
//
//  The title rides the user's meeting-summary model (`PromptModel.loadSelectedMeetingSummary`)
//  through `LLMProviderFactory` — the same seam the summary itself uses. It used to be a
//  hardwired Gemini call, which meant no titles at all without a Gemini key and none in
//  Offline Mode even when the summary had just been generated by a local model.
//

import Foundation

@MainActor
enum MeetingTitleService {

  /// Sessions whose title call is currently in flight. The menu-bar observer and the chat
  /// backfill can both call in for one meeting; without this set both would pass the
  /// title-empty pre-check and fire two title calls.
  private static var inFlight: Set<UUID> = []

  /// Generates a short title for the meeting chat session `sessionId` from its finished summary
  /// and persists it in the store. Returns the applied title, or nil when nothing was written
  /// (already titled, no summary text, Offline Mode with a cloud summary model, no credential
  /// for the summary model's provider, or the call failed — each logged, never surfaced as a
  /// popup: a missing title is cosmetic).
  static func generateAndPersistTitle(sessionId: UUID, summary: String) async -> String? {
    guard let target = ChatSessionStore.shared.session(by: sessionId),
      ChatViewModel.meetingTitleNeedsGeneration(target)
    else { return nil }
    guard !inFlight.contains(sessionId) else { return nil }
    inFlight.insert(sessionId)
    defer { inFlight.remove(sessionId) }
    let summaryText = summary.trimmingCharacters(in: .whitespacesAndNewlines)
    guard !summaryText.isEmpty else { return nil }

    // The title rides the meeting-summary model — the same model that produced the summary, so
    // a local (MLX / local server) summary setup gets local titles too.
    let model = PromptModel.loadSelectedMeetingSummary()
    // Offline Mode blocks every cloud provider; the on-this-Mac ones (`ChatModelProvider.isLocal`)
    // may run. A cloud title call would only burn retries behind the offline URL guard.
    if OfflineMode.isEnabled, !model.provider.isLocal {
      DebugLogger.log(
        "TITLE-MEETING: Skipping title generation (Offline Mode, summary model \(model.rawValue) is cloud)")
      return nil
    }
    guard model.hasRequiredCredential else {
      DebugLogger.log(
        "TITLE-MEETING: Skipping title generation (no credential for summary model \(model.rawValue))")
      return nil
    }

    let prompt = """
      \(ChatDateContext.stableLine())

      Give this meeting a short title (2–4 words) that captures its main topic. \
      Begin with a single emoji that fits the topic, then one space, then the words. \
      Reply with only the title on a single line — no quotes, no trailing punctuation, no explanation. \
      Example: 🤝 Vendor Negotiation

      Meeting summary:
      \(String(summaryText.prefix(1200)))
      """
    do {
      // Structured output: the model must return {"title": "..."} — no free-text parsing.
      let titleSchema: [String: Any] = [
        "type": "object",
        "properties": [
          "title": [
            "type": "string",
            "description": "A short title capturing the core topic: a single leading emoji, then one space, then 2–4 words. No quotes, no trailing punctuation, no explanation. Example: 📊 Quarterly Revenue",
          ] as [String: Any],
        ] as [String: Any],
        "required": ["title"],
      ]
      // Lowest ThinkingLevel. A 2–4 word title needs no reasoning; `.default` would leave
      // Flash on its medium built-in. Models that reject `minimal` are clamped to their floor.
      let obj = try await MeetingListService.withRetry(label: "TITLE-MEETING") {
        try await LLMProviderFactory.provider(for: model).generateStructured(
          model: model.rawValue,
          contents: [["role": "user", "parts": [["text": prompt]]]],
          systemInstruction: nil,
          schema: titleSchema,
          schemaName: "meeting_title",
          thinkingLevel: .minimal)
      }
      let title = ChatViewModel.cleanTitleResponse((obj["title"] as? String) ?? "")
      guard !title.isEmpty else { return nil }
      // Re-read and re-check post-network: the user may have renamed the meeting (or a racing
      // path may have titled it) while the call was in flight. A manual rename never equals
      // the fallback, so `meetingTitleNeedsGeneration` preserves it.
      guard var updated = ChatSessionStore.shared.session(by: sessionId),
        ChatViewModel.meetingTitleNeedsGeneration(updated)
      else { return nil }
      let applied = String(title.prefix(ChatViewModel.maxSessionTitleLength))
      updated.title = applied
      ChatSessionStore.shared.save(updated)
      NotificationCenter.default.post(
        name: .chatSessionTitleChanged, object: nil,
        userInfo: ["sessionId": sessionId, "title": applied])
      DebugLogger.log("TITLE-MEETING: title generated for \(sessionId): \(title)")
      return applied
    } catch {
      DebugLogger.logError("TITLE-MEETING: title generation failed: \(error.logDescription)")
      return nil
    }
  }
}
